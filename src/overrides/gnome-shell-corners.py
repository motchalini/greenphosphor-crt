#!/usr/bin/env python3
"""Emit CSS that squares off the vendored shell theme's rounded corners.

Reads the vendored Graphite base of gnome-shell.css (everything before the
GreenPhosphor-CRT override marker) and re-emits every rule that sets
border-radius / -arrow-border-radius, with each length capped at MAX_PX.
build.sh appends the output ahead of gnome-shell-overrides.css, so each copy
lands after its original with the same selector and the same !important
(same weight, later wins). Every radius declaration is re-emitted, capped or
not, so the copies keep the base's own cascade order between rules.

Surfaces that should be fully square (the ones Blur my Shell backs with its
blur) are pinned to 0 by hand in gnome-shell-overrides.css, which comes after
this block.

Usage: gnome-shell-corners.py path/to/gnome-shell.css MARKER > corners.css
"""
import re
import sys

MAX_PX = 3

# Round by nature, not by styling: the hot-corner ripple, user avatars, and
# the screenshot UI's shutter button, drag handles and selection check.
# These are re-emitted with their original values.
KEEP = re.compile(r"ripple|user-icon|screenshot-ui-(capture-button|area-selector-handle"
                  r"|window-selector-check)")

PROPS = ("border-radius", "-arrow-border-radius")


def cap(value):
    """'14px' -> '3px', '0 0 6px 6px !important' -> '0 0 3px 3px !important'."""
    return re.sub(r"(\d+(?:\.\d+)?)px",
                  lambda m: f"{min(float(m.group(1)), MAX_PX):g}px", value)


def rules(css):
    """Yield (selectors, [(prop, value)]) for each rule that sets a radius."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        selectors = [" ".join(s.split()) for s in m.group(1).split(",")]
        decls = [(name, " ".join(value.split()))
                 for name, value in re.findall(r"([-\w]+)\s*:\s*([^;]+)", m.group(2))
                 if name in PROPS]
        if decls and any(selectors):
            yield [s for s in selectors if s], decls


def block(selectors, decls):
    body = "\n".join(f"  {name}: {value};" for name, value in decls)
    return ",\n".join(selectors) + " {\n" + body + "\n}"


def generate(css, marker):
    base = css.split(marker, 1)[0]
    out = [f"/* ---- corners: base radii capped at {MAX_PX}px "
           "(generated by gnome-shell-corners.py; do not edit) ---- */"]
    for selectors, decls in rules(base):
        capped = [s for s in selectors if not KEEP.search(s)]
        kept = [s for s in selectors if KEEP.search(s)]
        if capped:
            out.append(block(capped, [(n, cap(v)) for n, v in decls]))
        if kept:
            out.append(block(kept, decls))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    path, marker = sys.argv[1:3]
    with open(path, encoding="utf-8") as f:
        sys.stdout.write(generate(f.read(), marker))
